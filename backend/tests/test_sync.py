"""
Unit and Integration tests for Offline Synchronization Engine.
Verifies batch upload from offline mobile caches, idempotency, and delta sync.
"""

import pytest
from httpx import AsyncClient, ASGITransport
from app.main import app


@pytest.mark.asyncio
async def test_offline_batch_upload():
    transport = ASGITransport(app=app)
    async with AsyncClient(transport=transport, base_url="http://test") as client:
        batch_payload = {
            "asha_worker_id": "ASHA-KA-007",
            "device_id": "TABLET-RURAL-01",
            "sync_timestamp": "2026-11-21T10:00:00",
            "visits": [
                {
                    "client_id": "CLIENT-UUID-1001",
                    "recorded_at": "2026-11-21T09:30:00",
                    "visit_data": {
                        "beneficiary_id": "BEN-KA-001",
                        "beneficiary_name": "ಲಕ್ಷ್ಮಿ",
                        "visit_type": "ANC checkup",
                        "weight": 54.5,
                        "vaccinations_completed": ["TT injection"],
                        "vaccinations_due": [],
                        "next_visit_date": "2026-12-20",
                        "is_confirmed": True,
                        "transcript_raw": "ಲಕ್ಷ್ಮಿ ANC checkup, weight 54.5 kg"
                    }
                },
                {
                    "client_id": "CLIENT-UUID-1002",
                    "recorded_at": "2026-11-21T09:45:00",
                    "visit_data": {
                        "beneficiary_id": "BEN-KA-002",
                        "beneficiary_name": "ಸುಮಿತ್ರಾ",
                        "visit_type": "ANC checkup",
                        "weight": 51.0,
                        "vaccinations_completed": [],
                        "vaccinations_due": [],
                        "is_confirmed": True,
                        "transcript_raw": "ಸುಮಿತ್ರಾ bleeding agtidhe vaginal bleeding emergency",
                        "danger_flag": True
                    }
                }
            ],
            "pending_followups": []
        }

        res = await client.post("/api/sync/batch", json=batch_payload)
        assert res.status_code == 200
        data = res.json()
        assert data["status"] == "SUCCESS"
        assert data["synced_visits_count"] == 2
        assert data["synced_followups_count"] >= 2  # Generated by follow-up engine
        assert len(data["mappings"]) == 2
        assert data["mappings"][0]["client_id"] == "CLIENT-UUID-1001"
        assert data["mappings"][0]["server_id"].startswith("VIS-")


@pytest.mark.asyncio
async def test_sync_delta():
    transport = ASGITransport(app=app)
    async with AsyncClient(transport=transport, base_url="http://test") as client:
        res = await client.get("/api/sync/delta?since=2026-11-20T00:00:00")
        assert res.status_code == 200
        data = res.json()
        assert "server_timestamp" in data
        assert len(data["beneficiaries"]) >= 5
        assert isinstance(data["visits"], list)
        assert isinstance(data["followups"], list)
