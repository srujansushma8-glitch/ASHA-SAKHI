"""
Pydantic schemas for Followup tasks generated by the follow-up engine.
"""

from pydantic import BaseModel, Field
from typing import Optional


class FollowupCreate(BaseModel):
    visit_id: Optional[str] = None
    beneficiary_id: str
    task_type: str  # ANC_CHECKUP, VACCINATION, NEWBORN_CARE, DANGER_SIGN_CHECK, HOME_VISIT
    due_date: str  # YYYY-MM-DD
    priority: str = "MEDIUM"  # CRITICAL, HIGH, MEDIUM, LOW
    completion_status: str = "PENDING"  # PENDING, COMPLETED, OVERDUE
    notes: Optional[str] = None
    guideline_source: str


class FollowupResponse(FollowupCreate):
    id: str
    created_at: str
    beneficiary_name: Optional[str] = None
    beneficiary_name_kn: Optional[str] = None
    village: Optional[str] = None
    category: Optional[str] = None
    status: Optional[str] = None
    type: Optional[str] = None
    risk_level: Optional[str] = None
    phone: Optional[str] = None
    household_id: Optional[str] = None


class FollowupStatusUpdate(BaseModel):
    status: Optional[str] = None
    completion_status: Optional[str] = None
    due_date: Optional[str] = None
    notes: Optional[str] = None
