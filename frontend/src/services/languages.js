export const getLanguageByCode = (code) => {
  const norm = (code || 'kn').toLowerCase().split('-')[0].trim();
  return INDIC_LANGUAGES.find(l => l.code === norm) || INDIC_LANGUAGES[0];
};

export const isRtlLanguage = (code) => {
  const lang = getLanguageByCode(code);
  return lang?.dir === 'rtl';
};
